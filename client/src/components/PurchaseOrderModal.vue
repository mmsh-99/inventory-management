<script setup>
import { computed, ref, watch } from 'vue'
import { useI18n } from '../composables/useI18n'
import { api } from '../api'

const { translateProductName } = useI18n()

const props = defineProps({
  isOpen: {
    type: Boolean,
    default: false
  },
  backlogItem: {
    type: Object,
    default: null
  },
  mode: {
    type: String,
    default: 'create'
  }
})

const emit = defineEmits(['close', 'po-created'])

const shortage = computed(() => {
  if (!props.backlogItem) return 0
  return props.backlogItem.quantity_needed - props.backlogItem.quantity_available
})

const form = ref({
  supplier_name: '',
  quantity: 0,
  unit_cost: 0,
  expected_delivery_date: '',
  notes: ''
})

const submitting = ref(false)
const submitError = ref(null)

const purchaseOrder = ref(null)
const loadingPO = ref(false)
const viewError = ref(null)

const resetForm = () => {
  submitError.value = null
  form.value = {
    supplier_name: '',
    quantity: shortage.value > 0 ? shortage.value : 1,
    unit_cost: 0,
    expected_delivery_date: '',
    notes: ''
  }
}

const loadPurchaseOrder = async () => {
  if (!props.backlogItem) return

  if (props.backlogItem.purchase_order) {
    purchaseOrder.value = props.backlogItem.purchase_order
    return
  }

  loadingPO.value = true
  viewError.value = null
  try {
    purchaseOrder.value = await api.getPurchaseOrderByBacklogItem(props.backlogItem.id)
  } catch (err) {
    viewError.value = 'Failed to load purchase order details'
    console.error(err)
  } finally {
    loadingPO.value = false
  }
}

watch([() => props.isOpen, () => props.backlogItem, () => props.mode], () => {
  if (!props.isOpen || !props.backlogItem) return

  if (props.mode === 'create') {
    resetForm()
  } else {
    purchaseOrder.value = null
    loadPurchaseOrder()
  }
}, { immediate: true })

const totalCost = computed(() => {
  if (!purchaseOrder.value) return 0
  return purchaseOrder.value.quantity * purchaseOrder.value.unit_cost
})

const statusBadgeClass = computed(() => {
  if (!purchaseOrder.value) return ''
  const status = purchaseOrder.value.status.toLowerCase()
  if (status === 'pending') return 'warning'
  if (status === 'delivered' || status === 'completed') return 'success'
  return 'info'
})

const close = () => {
  emit('close')
}

const submitPO = async () => {
  if (!props.backlogItem) return

  submitting.value = true
  submitError.value = null
  try {
    const poData = await api.createPurchaseOrder({
      backlog_item_id: props.backlogItem.id,
      supplier_name: form.value.supplier_name,
      quantity: form.value.quantity,
      unit_cost: form.value.unit_cost,
      expected_delivery_date: form.value.expected_delivery_date,
      notes: form.value.notes
    })
    emit('po-created', poData)
  } catch (err) {
    submitError.value = err.response?.data?.detail || 'Failed to create purchase order'
    console.error(err)
  } finally {
    submitting.value = false
  }
}

const formatDate = (dateString) => {
  if (!dateString) return 'N/A'
  const date = new Date(dateString)
  if (isNaN(date.getTime())) return 'N/A'
  return date.toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  })
}
</script>

